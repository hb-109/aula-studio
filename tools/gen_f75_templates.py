"""Generate Sources/AulaCore/F75Captured.swift from a hid.dll logger capture.

Usage: python3 -I tools/gen_f75_templates.py captures/aula-hid-log-2.txt

The F75 Pro's onboard writes replace whole tables (the colour palette and the
four key-assignment pages), and AULA's driver builds those tables from its own
defaults. This copies the factory tables out of a recording of AULA's driver, so
AULA Studio starts from exactly the bytes AULA sends, plus a few recorded packets
that SelfCheck must reproduce byte for byte.
"""
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
rows = []
for line in open(sys.argv[1]):
    p = line.split()
    if len(p) > 5 and p[1] in ("SET", "GET"):
        rows.append((p[0], p[1], bytes(int(x, 16) for x in p[5:])))


def sets(cmd):
    return [(t, b) for t, tag, b in rows if tag == "SET" and b[1] == cmd]


def gets(cmd):
    return [(t, b) for t, tag, b in rows if tag == "GET" and b[1] == cmd]


# Factory palette: the first 0a write, before any colour was changed.
palette = sets(0x0A)[0][1][8:8 + 512]

# Key-assignment pages: the recorded write had F1 (LED 12) bound to a macro;
# put F1 back to its plain key so the template is the factory layout.
pages = [b[8:8 + 512] for _, b in sets(0x03)]
page0 = bytearray(pages[0])
assert page0[12 * 4:12 * 4 + 4] == bytes([0x03, 0x01, 0x01, 0x00]), "expected F1 = macro in the capture"
page0[12 * 4:12 * 4 + 4] = bytes([0x00, 0x00, 0x00, 0x3A])
factory_pages = [bytes(page0)] + pages[1:]

# Recorded settings round trips: (block read with 84, block written with 04).
reads = gets(0x84)
writes = sets(0x04)
pairs = []
for (tr, r), (tw, w) in zip(reads, writes):
    pairs.append((tr, r[8:136], w[8:136]))


def hexlit(b):
    return '"' + b.hex() + '"'


out = [
    "// Generated by tools/gen_f75_templates.py from a recording of AULA's F75 driver. Do not edit by hand.",
    "",
    "/// Tables and packets recorded from AULA's own driver talking to an F75 Pro.",
    "public enum F75Captured {",
    "    /// Factory colour palette (command 0a payload, 512 bytes).",
    f"    public static let factoryPalette = F75Captured.bytes({hexlit(palette)})",
    "",
    "    /// Factory key assignments: Default, FN1, FN2 and Tap layers (command 03, pages 0-3, 512 bytes each).",
    "    public static let factoryKeymapPages: [[UInt8]] = [",
]
for p in factory_pages:
    out.append(f"        F75Captured.bytes({hexlit(p)}),")
out += [
    "    ]",
    "",
    "    /// The full recorded key-assignment write (F1 bound to macro 1), for SelfCheck.",
    "    public static let recordedKeymapPages: [[UInt8]] = [",
]
for p in pages:
    out.append(f"        F75Captured.bytes({hexlit(p)}),")
out += [
    "    ]",
    "",
    "    /// Every recorded settings round trip: the 128-byte block read (84) and the block AULA wrote back (04).",
    "    public static let settingsRoundTrips: [(time: String, read: [UInt8], written: [UInt8])] = [",
]
for t, r, w in pairs:
    out.append(f'        ("{t}", F75Captured.bytes({hexlit(r)}), F75Captured.bytes({hexlit(w)})),')
out += [
    "    ]",
    "",
    "    /// Recorded palette writes in order (0a payloads), for SelfCheck.",
    "    public static let recordedPalettes: [(time: String, table: [UInt8])] = [",
]
for t, b in sets(0x0A):
    out.append(f'        ("{t}", F75Captured.bytes({hexlit(b[8:8 + 512])})),')
macro = sets(0x05)[0][1]
length = macro[6] | (macro[7] << 8)
out += [
    "    ]",
    "",
    "    /// The recorded macro write (05): a macro named \"test\" typing A then B.",
    f"    public static let recordedMacroReport = F75Captured.bytes({hexlit(macro[:8 + length])})",
    "",
    "    static func bytes(_ hex: String) -> [UInt8] {",
    "        var out: [UInt8] = []",
    "        out.reserveCapacity(hex.count / 2)",
    "        var i = hex.startIndex",
    "        while i < hex.endIndex {",
    "            let j = hex.index(i, offsetBy: 2)",
    "            out.append(UInt8(hex[i..<j], radix: 16)!)",
    "            i = j",
    "        }",
    "        return out",
    "    }",
    "}",
    "",
]
dest = root / "Sources" / "AulaCore" / "F75Captured.swift"
dest.write_text("\n".join(out), encoding="utf-8")
print(f"wrote {dest}: {len(pairs)} settings round trips, {len(sets(0x0A))} palettes, {len(pages)} keymap pages")
